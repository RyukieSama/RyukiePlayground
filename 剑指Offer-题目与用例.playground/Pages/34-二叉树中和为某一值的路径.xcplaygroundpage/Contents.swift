# 34-二叉树中和为某一值的路径

## 题目

输入一棵二叉树和一个整数，打印出二叉树中节点值的和为输入整数的所有路径。从树的根节点开始往下一直到叶节点所经过的节点形成一条路径。

## 用例

**输入：** `root = [5,4,8,11,null,13,4,7,2,null,null,5,1]`，`target = 22`

**输出：** `[[5,4,11,2], [5,8,4,5]]`

## 提示

节点总数 <= 10000

