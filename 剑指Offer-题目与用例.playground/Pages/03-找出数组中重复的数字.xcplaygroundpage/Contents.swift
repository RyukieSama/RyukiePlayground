## 错误解析

### 1. 原来的 `enumerated()` 会让值与数组状态不同步

`nums.enumerated()` 基于开始遍历时的数组生成序列。循环内执行 `swapAt` 后，
局部数组已经发生变化，但后续取得的 `val` 仍可能来自原来的遍历序列。

因此，下面三个值可能不再描述同一个状态：

- `idx`：当前遍历下标
- `val`：遍历序列提供的旧值
- `nums[idx]`：交换后位于该下标的新值

### 2. 初版的 `while` 在交换后过早移动了指针

一次交换只能确保值为 `val` 的元素被放到下标 `val`，但交换到 `p` 位置的
新元素不一定已经处于正确位置。因此，执行 `swapAt` 后不能立即执行 `p += 1`，
而是应该留在当前下标继续检查。

例如：

```
nums = [0, 2, 0]

p = 0：nums[0] == 0，移动到下一位
p = 1：交换 nums[1] 和 nums[2]
       数组变为 [0, 0, 2]
```

交换后再次检查 `p = 1`，才能发现 `nums[1]` 与 `nums[0]` 都是 `0`。
如果此时直接移动到 `p = 2`，这个重复数字就会被漏掉。

## 注意事项

- 只有当 `nums[p] == p` 时，才说明当前位置已经整理完成，此时才能执行 `p += 1`。
- 执行交换后应保留当前下标，并在下一轮重新读取 `nums[p]`。
- 访问 `nums[val]` 依赖题目条件：所有数字必须位于 `0...n-1`，否则可能数组越界。
- `0` 是合法数字，也可能就是重复数字，不能用 `return 0` 表示“没有找到”。
  若需要异常兜底值，可以使用 `-1`。
- `var nums = nums` 不会修改调用方传入的数组；但 Swift 数组采用写时复制，
  首次修改局部副本时可能产生一次完整复制。
*/

func find_20260914_02(_ nums: [Int]) -> Int {
    // 双指针 + 哈希表
    var dp: [Int: Int] = [:], left = 0, right = nums.count - 1
//    while left < right {// 奇数会漏掉中间的
    while left <= right {
        let leftV = nums[left], rightV = nums[right]
        
        if left == right {
            return dp[leftV] == nil ? -1 : leftV
        }
        
        if let _ = dp[leftV] {
            return leftV
        }
        else {
            dp[leftV] = 1
            left += 1
        }
        
        if let _ = dp[rightV] {
            return rightV
        }
        else {
            dp[rightV] = 1
            right -= 1
        }
    }
    return -1
}

find_20260914_02(datas)

/*:
## 双指针 + 哈希表：总结

### 最终结论

当前实现是正确的。左右指针分别从数组两端向中间移动，哈希表记录已经访问过的数字：

- 数字第一次出现时，将它记录到哈希表。
- 如果哈希表中已经存在当前数字，说明找到了重复数字。
- 左右指针相遇时，中间元素只检查一次：它已存在于哈希表时返回该元素，否则返回 `-1`。

### 刚才出现的错误

#### 1. 误认为这是二分法或动态规划

这段代码没有利用有序数组，也没有每次排除一半搜索范围，所以不是二分法；
同时没有定义子问题和状态转移关系，所以也不是动态规划。

准确名称是“双指针 + 哈希表”。双指针只是改变了遍历顺序，并没有降低时间复杂度。

#### 2. 使用 `left < right` 漏掉中间元素

数组长度为奇数时，左右指针最终会指向同一个中间元素。`left < right` 会直接结束循环，
导致中间元素没有被记录或检查。

例如：

```
nums = [0, 0, 1]
```

两端的 `0` 和 `1` 被处理后，指针在中间的 `0` 相遇。如果不检查中间元素，
函数会错误返回 `-1`。

#### 3. 直接使用 `left <= right` 可能重复处理中间元素

当 `left == right` 时，`leftV` 和 `rightV` 来自同一个数组位置。如果仍然依次执行
左右两段逻辑，左侧会先记录该元素，右侧随后便会把同一个元素误判为重复。

最终实现通过单独处理 `left == right`，保证中间元素只检查一次。

### 正确性依据

循环开始时，哈希表保存所有已经从左右两端访问过的数字。每轮最多处理两个尚未访问的位置：

- 任意重复数字的第二次出现都会命中哈希表并立即返回。
- 偶数长度数组最终会变成 `left > right`，所有位置恰好处理一次。
- 奇数长度数组最终会出现 `left == right`，中间位置由单独分支处理一次。

因此，函数不会漏查或重复处理任何数组位置。

### 复杂度

- 时间复杂度：`O(n)`
- 空间复杂度：`O(n)`

这里只需要记录数字是否出现过，使用 `Set<Int>` 会比 `[Int: Int]` 更贴合语义，
但不会改变时间和空间复杂度。
*/

