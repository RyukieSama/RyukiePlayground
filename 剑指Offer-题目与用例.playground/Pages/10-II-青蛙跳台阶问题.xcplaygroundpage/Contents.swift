/*:
# 10-II-青蛙跳台阶问题

## 题目

一只青蛙一次可以跳上1级台阶，也可以跳上2级台阶。求该青蛙跳上一个 n 级的台阶总共有多少种跳法。

答案需要取模 1e9+7（1000000007），如计算初始结果为：1000000008，请返回 1。

## 用例 1

**输入：** n = 2
**输出：** 2
## 用例 2

**输入：** n = 7
**输出：** 21
## 用例 3

**输入：** n = 0
**输出：** 1
## 提示

0 <= n <= 100

## 来源

[LeetCode 原题](https://leetcode-cn.com/problems/qing-wa-tiao-tai-jie-wen-ti-lcof)
*/

var d: [Int: Int] = [:]

func jump(_ n: Int) -> Int {
    var res: Int = 0
    // 本质是看 n-1 和 n-2 加起来有多少种，斐波拉契数列的变种
    switch n {
    case 0, 1:
        res = 1
    default:
        if let v = d[n-1] {
            res += v
        }
        else {
            res += jump(n-1)
        }
        
        if let v = d[n-2] {
            res += v
        }
        else {
            res += jump(n-2)
        }
    }
    d[n] = res
    return res % 1000000007
}

jump(5)

/*:
## 青蛙跳台阶：总结

### 状态转移

到达第 `n` 级台阶的最后一步只有两种情况：

- 从第 `n - 1` 级跳 1 级。
- 从第 `n - 2` 级跳 2 级。

因此：

```
jump(n) = jump(n - 1) + jump(n - 2)
```

边界状态为：

```
jump(0) = 1
jump(1) = 1
```

`jump(0) = 1` 表示“不跳”这一种方式，这是递推关系能够成立的必要条件。

### 当前实现的正确部分

当前代码使用字典 `d` 缓存已经计算过的状态，并且在第 56 行写入：

```swift
d[n] = res
```

因此，相同的 `jump(n)` 不会被重复递归计算。它属于“记忆化递归”，
本质上是自顶向下的动态规划。

### 取模处理

返回值在第 57 行进行了取模：

```swift
return res % 1000000007
```

这能保证递归返回给上一层的结果较小，当前题目 `n <= 100` 时不会因为递归返回值而溢出。

但当前缓存保存的是取模前的 `res`，而不是最终结果。更规范的做法是先计算：

```
result = res % 1_000_000_007
d[n] = result
return result
```

这样字典中的每个值都保持在模数范围内，后续查缓存时也更安全。

### 复杂度

缓存生效后，每个 `n` 只会计算一次：

- 时间复杂度：`O(n)`
- 字典空间：`O(n)`
- 递归栈空间：`O(n)`
- 总空间复杂度：`O(n)`

如果改成循环并只保留前两个状态，可以将额外空间降为 `O(1)`。

### 常见错误

- 忘记写入 `d[n]`，会退化为普通递归，时间复杂度变成 `O(2ⁿ)`。
- 把 `jump(0)` 写成 `0`，会导致所有结果都偏小。
- 每次递归都重新创建缓存，记忆化将无法生效。
- 只在最外层取模，可能在中间加法时发生整数溢出；应让每个状态都保持在模数范围内。

### 输入限制

当前实现默认 `n >= 0`。如果传入负数，会进入 `default` 分支并继续递归，
最终导致栈溢出。题目已保证 `0 <= n <= 100`，所以不影响本题。

此外，全局字典 `d` 会保留多次调用之间的缓存。对于纯函数式实现，
可以将它改为函数内部的 `memo`，减少共享可变状态。
*/
// 只用两个值 结合循环 优化空间
func loopJump(_ n: Int) -> Int {
    guard n > 2 else {
        return 1
    }
    
    var c1 = 1, c2 = 1, v = 2
    
    while v <= n {
        let newC2 = c2 + c1
        c1 = c2
        c2 = newC2 % 1000000007
        v += 1
    }
    
    return c2
}

loopJump(7)

/*:
## 循环优化版：总结

### 状态含义

循环版本不再保存所有历史结果，只保留计算下一项所需的两个状态：

- `c1`：前前一项的跳法数量
- `c2`：前一项的跳法数量

初始时：

```
c1 = jump(0) = 1
c2 = jump(1) = 1
```

### 状态更新

第 `v` 阶的结果由前两阶相加得到：

```
newC2 = c1 + c2
c1 = c2
c2 = newC2
```

更新后：

- 原来的 `c2` 成为新的 `c1`
- 新计算出的结果成为新的 `c2`

因此每轮循环结束时，`c2` 始终表示当前阶数的答案。

### 循环边界

`n = 0` 和 `n = 1` 的答案都是 `1`，由 `guard` 直接返回。
当 `n >= 2` 时，从第 2 阶开始计算，一直计算到第 `n` 阶：

```
v = 2
while v <= n
```

循环结束后，`c2` 就是 `jump(n)`。

注意：如果把条件写成 `n > 2`，`n = 2` 会被错误地直接返回 `1`；
这里必须保证 `n = 2` 能进入循环。

### 取模

新状态在第 155 行取模：

```swift
c2 = newC2 % 1000000007
```

这样每个状态都保持在模数范围内，后续加法不会因为斐波那契数增长而溢出。
取模不会改变递推结果，因为：

```
(a + b) % M == ((a % M) + (b % M)) % M
```

### 正确性依据

每轮循环都根据：

```
jump(v) = jump(v - 1) + jump(v - 2)
```

计算当前状态，并将两个变量向前移动一位。初始状态 `jump(0)` 和 `jump(1)`
正确，所以通过数学归纳，循环结束时得到的 `c2` 就是 `jump(n)`。

### 复杂度

- 时间复杂度：`O(n)`
- 额外空间复杂度：`O(1)`

相比记忆化递归版本，循环版本不需要字典，也没有递归调用栈，
只使用 `c1`、`c2` 和循环变量 `v`。

### 与记忆化递归的对比

| 实现 | 时间复杂度 | 空间复杂度 | 特点 |
| --- | --- | --- | --- |
| 普通递归 | `O(2ⁿ)` | `O(n)` | 大量重复计算 |
| 记忆化递归 | `O(n)` | `O(n)` | 代码直观，保存所有状态 |
| 循环滚动变量 | `O(n)` | `O(1)` | 只保留前两个状态，空间最优 |
*/

