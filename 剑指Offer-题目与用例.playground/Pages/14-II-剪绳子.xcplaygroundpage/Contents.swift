/*:
# 14-II-剪绳子

## 题目

给你一根长度为 n 的绳子，请把绳子剪成整数长度的 m 段（m、n都是整数，n>1并且m>1），每段绳子的长度记为 k[0],k[1]...k[m - 1] 。请问 k[0]*k[1]*...*k[m - 1] 可能的最大乘积是多少？例如，当绳子的长度是8时，我们把它剪成长度分别为2、3、3的三段，此时得到的最大乘积是18。

答案需要取模 1e9+7（1000000007），如计算初始结果为：1000000008，请返回 1。

## 用例 1

```Swift
输入: 2
输出: 1
解释: 2 = 1 + 1, 1 × 1 = 1
```

## 用例 2

```Swift
输入: 10
输出: 36
解释: 10 = 3 + 3 + 4, 3 × 3 × 4 = 36
```

## 提示

2 <= n <= 1000

注意：本题与[主站 343 题](https://leetcode-cn.com/problems/integer-break/)相同

## 来源

[LeetCode 原题](https://leetcode-cn.com/problems/integer-break/)
*/
let mod = 1000000007

func cut1(n: Int) -> Int {
    var res = 1
    
    if n <= 3 { // 必须剪开
        res = n - 1
    }
    else {
        let v = n % 3, x = n / 3
        
        if v == 0 {
            // 可以全部切成 3 求 3 的 x 次方
            res = mi(n: 3, count: x)
        }
        else if v == 1 {
            // 剩 1 那就留一个 4
            res = mi(n: 3, count: x - 1) * 4
        }
        else if v == 2 {
            // 剩 2 就不切了
            res = mi(n: 3, count: x) * 2
        }
    }
    
    return res % mod
}

func mi(n: Int, count: Int) -> Int {
    var res = 1
    for _ in 0..<count {
        res = res * n % mod
    }
    return res
}

/*:
## 14-II 解题解析

### 核心思路：贪心

在绳子总长度固定时，乘积最大时应尽可能拆出长度为 `3` 的部分。设：

```swift
let v = n % 3
let x = n / 3
```

根据余数分三种情况：

- `v == 0`：全部拆成 `3`，结果是 `3^x`。
- `v == 1`：不能保留一个 `1`，应把 `3 + 1` 改成 `2 + 2`，结果是 `3^(x - 1) × 4`。
- `v == 2`：保留一个 `2`，结果是 `3^x × 2`。

例如 `n = 10`：

```text
10 = 3 + 3 + 4
结果 = 3 × 3 × 4 = 36
```

### 边界条件

题目要求至少剪成两段，因此：

```text
n = 2 → 1 + 1 → 1
n = 3 → 1 + 2 → 2
```

所以 `n <= 3` 时返回 `n - 1`，不能直接把 `n` 当作一段返回。

### 取模处理

14-II 的结果需要对 `1_000_000_007` 取模。`mi` 中每次乘法后立即取模：

```swift
res = res * n % mod
```

这样可以避免中间结果不断增大。`0..<count` 表示恰好计算 `n^count`，当 `count == 0` 时循环不执行，结果保持为 `1`。

### 复杂度

- 时间复杂度：`O(n)`，当前 `mi` 使用循环计算幂。
- 空间复杂度：`O(1)`。

如果使用二进制快速幂，时间复杂度还可以优化为 `O(log n)`。
*/

