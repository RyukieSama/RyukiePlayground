/*:
# 14-I-剪绳子

## 题目

给你一根长度为 n 的绳子，请把绳子剪成整数长度的 m 段（m、n都是整数，n>1并且m>1），每段绳子的长度记为 k[0],k[1]...k[m-1] 。

请问 k[0]*k[1]*...*k[m-1] 可能的最大乘积是多少？

例如，当绳子的长度是8时，我们把它剪成长度分别为2、3、3的三段，此时得到的最大乘积是18。

## 用例 1

```
输入: 2
输出: 1
解释: 2 = 1 + 1, 1 × 1 = 1
```

## 用例 2

```
输入: 10
输出: 36
解释: 10 = 3 + 3 + 4, 3 × 3 × 4 = 36
```

## 提示

2 <= n <= 58

注意：本题与主站 343 题相同：https://leetcode-cn.com/problems/integer-break/

## 来源

[LeetCode 原题](https://leetcode-cn.com/problems/integer-break/)
*/

func cut(n: Int) -> Int {
    var d: [Int: Int] = [
        2: 1,
    ]
    
    for x in 2...n {
        for y in 1..<x {
            d[x] = max(d[x] ?? -1, y * (x - y), y * (d[x - y] ?? -1))
        }
    }
    
    return d[n] ?? -1
}


func cut2(length: Int) -> Int {
    var d: [Int] = Array(repeating: 0, count: length + 1)
    d[2] = 1 // 这题的动态规划用数组更合适
    
    for n in 2...length {
        for m in 1..<n {
            d[n] = max(d[n], m * (n-m), m * d[n-m])
        }
    }
    
    return d[length]
}

/*:
## `cut2` 动态规划解析

### 状态定义

`d[x]` 表示长度为 `x` 的绳子剪成至少两段后，可以得到的最大乘积。

### 状态转移

假设第一次剪下长度为 `m` 的一段，剩余长度为 `n - m`，有两种选择：

1. 剩余部分不再剪，乘积为：

```swift
m * (n - m)
```

2. 剩余部分继续剪，使用剩余部分的最优结果：

```swift
m * d[n - m]
```

因此需要在所有 `m` 中取最大值：

```swift
d[n] = max(d[n], m * (n - m), m * d[n - m])
```

### 初始化

长度为 `2` 时只能剪成 `1 + 1`，所以：

```swift
d[2] = 1
```

数组创建为 `length + 1`，是为了可以直接使用 `d[length]`，并让数组下标与绳子长度对应。

### 为什么循环到 `n - 1`

第一次剪下的长度必须满足：

```text
1 <= m < n
```

如果 `m == n`，剩余长度为 `0`，并没有真正剪成两段。因此当前使用 `1..<n` 是正确的。

### 例子：`n = 4`

尝试不同的第一次切法：

```text
1 + 3 → 1 × 3 = 3
2 + 2 → 2 × 2 = 4
3 + 1 → 3 × 1 = 3
```

所以 `d[4] = 4`。

### 复杂度

- 时间复杂度：`O(n²)`，每个长度都要尝试多个第一次切法。
- 空间复杂度：`O(n)`，用于保存动态规划数组。
*/

