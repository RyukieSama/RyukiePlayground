# 50-第一个只出现一次的字符

## 题目

在字符串 s 中找出第一个只出现一次的字符。如果没有，返回一个单空格。 s 只包含小写字母。

## 用例 1

**输入：** s = "abaccdeff"

**输出：** 'b'

## 用例 2

**输入：** s = ""

**输出：** ' '

## 约束

0 <= s 的长度 <= 50000

## 来源

[LeetCode 原题](https://leetcode-cn.com/problems/di-yi-ge-zhi-chu-xian-yi-ci-de-zi-fu-lcof)
*/

func findChr(_ str: String) -> String {
    var chars = Array(str).map({ String($0) })
    var d: [String: Int] = [:]
    
    for c in chars {
        if let v = d[c] {
            d[c] = v + 1
        }
        else {
            d[c] = 1
        }
    }
    
    for c in chars {
        if let v = d[c], v == 1 {
            return c
        }
    }
    
    return " "
}

/*:
## 题目解析

这道题要求返回字符串中第一个只出现一次的字符。当前解法使用两次遍历：

1. 第一次遍历，统计每个字符出现的次数。
2. 第二次按照原字符串顺序遍历，找到第一个次数为 `1` 的字符。

第二次遍历必须按照原顺序进行，不能直接遍历字典，因为字典中的顺序不能代表字符在原字符串中的位置。

例如 `"abaccdeff"` 的统计结果中，`b`、`d`、`e` 都只出现一次，但按照原字符串顺序，`b` 最先出现，所以应该返回 `b`。

### 当前字典解法

字典适用于字符范围未知的情况：

- 键是字符；
- 值是该字符出现的次数。

当前实现能够正确处理空字符串、所有字符重复以及只有一个字符的情况。没有找到符合条件的字符时返回单个空格，也符合题目要求。

### 固定数组优化

题目明确说明字符串只包含小写字母，因此也可以用长度为 `26` 的数组统计：

- `0` 对应 `a`；
- `1` 对应 `b`；
- ……；
- `25` 对应 `z`。

数组不需要计算哈希，常数开销比字典更小，但只能适用于字符范围固定的场景。

### 为什么不能只遍历一次

遍历到一个字符时，还不知道它后面是否会再次出现。因此需要先完成计数，再进行第二次扫描，才能确定“只出现一次”并且保证它是最先出现的字符。

### 复杂度

- 时间复杂度：`O(n)`，最多遍历字符串两次。
- 字典解法空间复杂度：`O(k)`，`k` 是不同字符的数量。
- 固定 26 位数组的空间复杂度：`O(1)`。
*/

