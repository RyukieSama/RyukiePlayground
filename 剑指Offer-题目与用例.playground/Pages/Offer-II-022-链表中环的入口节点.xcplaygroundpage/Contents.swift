# Offer-II-022-链表中环的入口节点

## 题目

给定一个链表，返回链表开始入环的第一个节点。如果链表无环，则返回 `nil`。

使用整数 `pos` 表示链表尾连接到链表中的位置（索引从 0 开始）；`pos = -1` 表示链表无环。`pos` 只用于描述用例，不会作为参数传入。不得修改给定链表。

## 用例 1

**输入：** `head = [3,2,0,-4]`，`pos = 1`

**输出：** 返回索引为 `1` 的链表节点

## 用例 2

**输入：** `head = [1,2]`，`pos = 0`

**输出：** 返回索引为 `0` 的链表节点

## 用例 3

**输入：** `head = [1]`，`pos = -1`

**输出：** `nil`

## 约束

- 链表节点数在 `[0, 10⁴]` 范围内
- `-10⁵ <= Node.val <= 10⁵`
- `pos` 为 `-1` 或链表中的有效索引

