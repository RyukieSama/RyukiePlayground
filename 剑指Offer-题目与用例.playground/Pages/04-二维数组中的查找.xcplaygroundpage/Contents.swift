# 04-二维数组中的查找

## 题目

在一个 n * m 的二维数组中，

每一行都按照从左到右递增的顺序排序，

每一列都按照从上到下递增的顺序排序。

请完成一个高效的函数，输入这样的一个二维数组和一个整数，判断数组中是否含有该整数。

## 用例

**输入：**

```
matrix = [
  [1,  4,  7, 11, 15],
  [2,  5,  8, 12, 19],
  [3,  6,  9, 16, 22],
  [10,13, 14, 17, 24],
  [18,21, 23, 26, 30]
]
target = 5
```

**输出：** `true`

**输入：** 使用相同的 `matrix`，`target = 20`

**输出：** `false`

## 约束

0 <= n <= 1000

0 <= m <= 1000

注意：本题与主站 240 题相同：https://leetcode-cn.com/problems/search-a-2d-matrix-ii/

## 来源

[LeetCode 原题](https://leetcode-cn.com/problems/search-a-2d-matrix-ii/)
*/
let matrix = [
    [1,  4,  7, 11, 15],
    [2,  5,  8, 12, 19],
    [3,  6,  9, 16, 22],
    [10,13, 14, 17, 24],
    [18,21, 23, 26, 30]
  ]

func find_20260914_01_X(arr: [[Int]], tar: Int) -> Bool {
    guard let fir = arr.first else {
        return false
    }
    var xL = 0, xR = fir.count - 1, y = 0
    
    // ❌ 错误 1：不能只根据每行首元素确定唯一的目标行。
    // 各行的数值范围可能互相重叠。以 target = 5 为例：
    // 首元素依次为 1、2、3、10，最终 y 会退回到第 2 行，
    // 但 5 实际位于第 1 行，因此后续只搜索第 2 行会漏掉答案。
    while y < arr.count {
        if let yf = arr[y].first {
            if yf < tar {
                // ❌ 如果所有行的首元素都小于 tar，y 最终会等于 arr.count。
                // 例如当前矩阵中 tar = 20 时，循环结束后 y == 5。
                y += 1
            }
            else if yf > tar {
                // ❌ 退回一行只能说明该行首元素不大于 tar，
                // 不能说明 tar 一定在这一行，也不能排除更早的行。
                y -= 1
                break
            }
            else {
                return true
            }
        }
        else {
            return false
        }
    }
    
    // ❌ 错误 2：这里只判断了 y >= 0，没有判断 y < arr.count。
    // 当上面的循环因为 y == arr.count 而结束时，arr[y] 会下标越界。
    //
    // ❌ 错误 3：即使 y 没有越界，下面也只搜索一行；
    // 前面的步骤无法保证目标值就在这一行，所以整体仍可能漏解。
    while xL <= xR, y >= 0 {
        // tar = 20 时会在这里访问 arr[5]，导致运行时崩溃。
        let nums = arr[y]
        let lVal = nums[xL], rVal = nums[xR]
        
        // ⚠️ 注意：左右指针只是从两端进行线性遍历。
        // 这里没有根据大小关系排除一半区间，因此不属于二分查找，
        // 也没有真正利用“行内递增”这一条件。
        if lVal != tar {
            xL += 1
        }
        else {
            return true
        }
        
        if rVal != tar {
            xR -= 1
        }
        else {
            return true
        }
    }

    return false
}

func find_20260914_01(arr: [[Int]], tar: Int) -> Bool {
    guard let firLine = arr.first else { return false }
    // 从 右上角开始
    var x = firLine.count - 1, y = 0
    
    while x >= 0, y < arr.count {
        let val = arr[y][x]
        if val > tar {
            x -= 1
        }
        else if val < tar {
            y += 1
        }
        else {
            return true
        }
    }
    
    return false
}

find_20260914_01(arr: matrix, tar: 5)

/*:
## 右上角搜索：总结

### 核心思路

矩阵的每一行从左到右递增，每一列从上到下递增。右上角元素同时具有两个特点：

- 左侧元素不大于它。
- 下方元素不小于它。

因此，从右上角开始比较时，每一步都能安全排除一整行或一整列。

### 移动规则

设当前位置为 `arr[y][x]`：

- `arr[y][x] == tar`：找到目标值，返回 `true`。
- `arr[y][x] > tar`：当前列从当前位置向下的元素只会更大，因此排除当前列，执行 `x -= 1`。
- `arr[y][x] < tar`：当前行当前位置左侧的元素只会更小，因此排除当前行，执行 `y += 1`。

当 `x < 0` 或 `y == arr.count` 时，说明所有可能位置均已排除，返回 `false`。

### 为什么旧解法不正确

旧解法先根据每行首元素选择一行，然后只在这一行中查找。由于不同行的数值范围可能重叠，
仅凭首元素无法确定目标所在的唯一行，所以可能漏掉答案。

另外，当目标值大于所有行的首元素时，旧解法会令 `y == arr.count`，
随后访问 `arr[y]`，造成数组下标越界。

新解法不预先猜测目标行，而是利用行、列同时有序的条件逐步排除区域，因此不会出现上述问题。

### 正确性依据

每轮循环都会进行一次确定性的排除：

- 向左移动时，被排除列中的候选值均大于目标值。
- 向下移动时，被排除行中的候选值均小于目标值。

所以移动过程中不会排除可能等于目标值的位置。当搜索越过矩阵边界时，
矩阵中已经不存在尚未检查的候选区域。

### 边界条件

- 空矩阵直接返回 `false`。
- 第一行为空时，初始 `x == -1`，循环不会执行。
- 当前实现默认每一行长度相同，这符合题目的 `n × m` 矩阵条件。
- 如果传入不规则二维数组，访问 `arr[y][x]` 时仍可能越界。

### 复杂度

- 时间复杂度：`O(n + m)`
- 空间复杂度：`O(1)`

其中，`n` 是矩阵行数，`m` 是矩阵列数。搜索过程中最多向左移动 `m` 次、
向下移动 `n` 次。
