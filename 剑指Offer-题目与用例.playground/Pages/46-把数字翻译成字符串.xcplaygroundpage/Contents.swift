func transNumToString(_ num: Int) -> Int {
    let chars = Array(String(num))
    let count = chars.count
    
    var dp = Array(repeating: 0, count: count + 1)
    dp[0] = 1
    dp[1] = 1
    
    if count == 1 {
        return 1
    }
    
    for i in 2...count {
        dp[i] = dp[i - 1]
        
        let value = Int(String(chars[i - 2]) + String(chars[i - 1]))!
        if value >= 10 && value <= 25 {
            dp[i] += dp[i - 2]
        }
    }
    
    return dp[count]
}


/*:
## 题目解析

这道题要求计算一个数字有多少种不同的翻译方式。每一位数字可以单独翻译；相邻两位组成的数字如果在 `10...25` 范围内，也可以合并翻译。

### 当前实现的问题

`guard num < 10 else { return 1 }` 会导致所有大于等于 10 的输入直接返回 1，例如 `12258` 会错误返回 1。

两位数字也不能只通过字符串判断 `ab < "25"`：`25` 本身合法，而 `06` 虽然字符串小于 `25`，但不能作为两位数字翻译。应该把两位字符转换成整数，并判断是否属于 `10...25`。

### 动态规划定义

设 `dp[i]` 表示前 `i` 位数字的翻译方法数。处理第 `i` 位时：

- 当前数字单独翻译，贡献 `dp[i - 1]`。
- 如果最后两位组成 `10...25`，可以合并翻译，贡献 `dp[i - 2]`。

因此状态转移为：先令 `dp[i] = dp[i - 1]`，再根据最后两位是否在 `10...25` 中决定是否加上 `dp[i - 2]`。

初始状态是 `dp[0] = 1`、`dp[1] = 1`。`dp[0] = 1` 表示空前缀有一种基础方式，方便计算第一组两位数字。

### 示例：`12258`

```text
1      → 1 种
12     → 2 种
122    → 3 种
1225   → 5 种
12258  → 5 种
```

最后两位 `58` 不在 `10...25` 中，所以不能合并，结果仍然是 5。

### 注意事项

- 合法的两位数字范围是 `10...25`。
- 单个数字 `0` 可以翻译，但 `06` 不能作为一个整体翻译。
- `map` 字典只有在需要真正生成字符串时才有用；本题只统计数量，不需要使用它。

### 复杂度

- 时间复杂度：`O(n)`，`n` 是数字位数。
- 使用完整 `dp` 数组时，空间复杂度为 `O(n)`。
- 因为每次只依赖前两个状态，也可以进一步优化到 `O(1)` 空间。
*/
