/*:
# 60-n个骰子的点数

## 题目

把n个骰子扔在地上，所有骰子朝上一面的点数之和为s。输入n，打印出s的所有可能的值出现的概率。

你需要用一个浮点数数组返回答案，其中第 i 个元素代表这 n 个骰子所能掷出的点数集合中第 i 小的那个的概率。

## 用例 1

**输入：** 1

**输出：** [0.16667,0.16667,0.16667,0.16667,0.16667,0.16667]

## 用例 2

**输入：** 2

**输出：** [0.02778,0.05556,0.08333,0.11111,0.13889,0.16667,0.13889,0.11111,0.08333,0.05556,0.02778]

## 约束

1 <= n <= 11

## 来源

[LeetCode 原题](https://leetcode-cn.com/problems/nge-tou-zi-de-dian-shu-lcof)
*/

// 没怎么看懂
func rate(_ n: Int) -> [Double] {
    guard n > 0 else {
        return []
    }
    
    // dp[sum] 表示当前已经投掷的骰子，点数和为 sum 的组合数量。
    // 数组长度使用 6 * n + 1，方便直接用点数和作为下标。
    var dp = Array(repeating: 0, count: 6 * n + 1)
    
    // 只有一个骰子时，点数 1...6 各有一种组合。
    for sum in 1...6 {
        dp[sum] = 1
    }
    
    if n >= 2 {
        for dice in 2...n {
            // next 保存加入当前骰子后的组合数量。
            var next = Array(repeating: 0, count: 6 * n + 1)
            
            // 投掷 dice - 1 个骰子时，点数和范围是：
            // dice - 1 ... 6 * (dice - 1)
            for sum in (dice - 1)...(6 * (dice - 1)) {
                guard dp[sum] > 0 else {
                    continue
                }
                
                // 当前骰子可以投出 1...6，累加到新的点数和。
                for face in 1...6 {
                    next[sum + face] += dp[sum]
                }
            }
            
            dp = next
        }
    }
    
    // n 个骰子一共有 6^n 种等可能的投掷结果。
    var total = 1.0
    for _ in 0..<n {
        total *= 6
    }
    
    // 点数和的有效范围是 n...6*n，将组合数转换为概率。
    return (n...(6 * n)).map {
        Double(dp[$0]) / total
    }
}


/*:
## 题目解析

这道题要求计算投掷 `n` 个骰子后，每个可能点数和出现的概率。

### 状态定义

`dp[sum]` 表示当前已经投掷的骰子中，点数和为 `sum` 的组合数量。

只有一个骰子时，点数 `1...6` 各有一种组合，因此 `dp[1...6]` 都为 `1`。

### 状态转移

加入一个新骰子时，新骰子可能投出 `1...6`。如果之前的点数和是 `sum`，当前骰子投出 `face`，新的点数和就是 `sum + face`：

```swift
next[sum + face] += dp[sum]
```

这会把前一轮的每种组合分别扩展出 6 种情况。

### 概率计算

每个骰子有 6 种等可能结果，投掷 `n` 个骰子一共有 `6^n` 种等可能组合。因此某个点数和的概率是：

```text
该点数和的组合数量 / 6^n
```

最终可能的点数和范围是 `n...6*n`，因为每个骰子的最小点数是 `1`，最大点数是 `6`。

### 示例：两个骰子

两个骰子共有 `36` 种组合。点数和为 `7` 的组合有：

```text
(1,6)、(2,5)、(3,4)、(4,3)、(5,2)、(6,1)
```

因此概率为 `6 / 36 = 0.16667`。

### 复杂度

- 时间复杂度：`O(n^2)`，点数和范围最多为 `6n`，每个状态尝试 6 个骰子点数。
- 额外空间复杂度：`O(n)`，保存点数和对应的组合数量。
*/
