# 算法复杂度

算法复杂度用来描述：当输入规模变大时，算法需要消耗多少时间和额外空间。

通常使用大 O 符号（`Big O`）表示增长趋势，关注输入规模 `n` 变大后的变化，
而不是某台机器上的具体运行秒数。

## 一、时间复杂度

时间复杂度描述算法执行步骤数量随输入规模 `n` 的增长趋势。

### 常见级别

| 复杂度 | 名称 | 典型例子 |
| --- | --- | --- |
| `O(1)` | 常数 | 访问数组某个下标、字典查找（平均情况） |
| `O(log n)` | 对数 | 二分查找 |
| `O(n)` | 线性 | 遍历数组一次 |
| `O(n log n)` | 线性对数 | 归并排序、堆排序 |
| `O(n²)` | 平方 | 两层嵌套遍历、冒泡排序 |
| `O(2ⁿ)` | 指数 | 未剪枝的递归枚举子集 |
| `O(n!)` | 阶乘 | 枚举所有排列 |

增长速度通常满足：

```
O(1) < O(log n) < O(n) < O(n log n) < O(n²) < O(2ⁿ) < O(n!)
```

### 如何计算

#### 1. 忽略常数

```swift
for _ in 0..<n {
    print("一次操作")
}
```

循环执行 `n` 次，复杂度是 `O(n)`。即使循环体执行了 3 个固定步骤，
也只写成 `O(n)`，因为常数不影响增长趋势。

#### 2. 顺序代码相加后取最大项

```swift
for _ in 0..<n { }       // O(n)
for _ in 0..<n * n { }   // O(n²)
```

总复杂度为 `O(n + n²)`，最终保留增长更快的项，得到 `O(n²)`。

#### 3. 嵌套循环相乘

```swift
for _ in 0..<n {
    for _ in 0..<n {
        // 固定操作
    }
}
```

外层执行 `n` 次，内层每次执行 `n` 次，总次数是 `n × n`，因此为 `O(n²)`。

#### 4. 每次缩小一半是 O(log n)

```swift
var left = 0
var right = n
while left < right {
    let mid = (left + right) / 2
    // 每轮将搜索范围缩小约一半
    right = mid
}
```

范围经过 `n → n/2 → n/4 → ...`，大约执行 `log₂n` 轮，所以是 `O(log n)`。

## 二、空间复杂度

空间复杂度描述算法运行过程中使用的额外内存随 `n` 的增长趋势。

通常说的是“辅助空间”，不把题目要求返回的结果数组计入；但不同题目或面试官
可能有不同约定，回答时应说明自己的统计口径。

### 常见例子

```swift
var sum = 0
for value in nums {
    sum += value
}
```

只使用固定数量的变量，额外空间复杂度是 `O(1)`。

```swift
var seen = Set<Int>()
for value in nums {
    seen.insert(value)
}
```

集合最多保存 `n` 个元素，额外空间复杂度是 `O(n)`。

```swift
func depth(_ node: TreeNode?) -> Int {
    guard let node else { return 0 }
    return max(depth(node.left), depth(node.right)) + 1
}
```

递归调用会占用调用栈。若树高为 `h`，递归栈空间是 `O(h)`：

- 平衡二叉树：`h = log n`，空间为 `O(log n)`
- 退化成链表的二叉树：`h = n`，空间为 `O(n)`

## 三、几个容易混淆的点

- 时间复杂度不是实际耗时；实际耗时还受语言、硬件和常数因素影响。
- 两层循环不一定就是 `O(n²)`，要看内层循环的实际执行次数。
- 递归算法不仅要分析每次调用的工作，还要计算递归深度和额外数据结构。
- `Array.sorted()` 会创建新数组；Swift 的数组、字符串还可能发生写时复制，
  所以代码层面的空间开销要结合具体 API 判断。
- 平均复杂度、最好情况和最坏情况可能不同。没有特别说明时，通常报告最坏情况。
- 对本题中的 `n`、`m` 等多个输入规模，应分别写出复杂度，例如矩阵搜索为
  `O(n + m))，不要笼统地写成 `O(n))。

## 四、刷题时的回答模板

分析一道题时，可以依次问：

1. 核心操作最多执行多少次？
2. 是否存在嵌套循环或递归？
3. 是否每轮将问题规模缩小一半？
4. 是否创建了与输入规模相关的数组、字典、集合或队列？
5. 递归深度最多是多少？

最后分别给出：

```
时间复杂度：O(...)
空间复杂度：O(...)
```
