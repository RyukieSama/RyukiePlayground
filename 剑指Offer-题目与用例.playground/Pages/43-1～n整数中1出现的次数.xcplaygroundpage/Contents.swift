# 43-1～n整数中1出现的次数

## 题目

输入一个整数 n ，求1～n这n个整数的十进制表示中1出现的次数。

例如，输入12，1～12这些整数中包含1 的数字有1、10、11和12，1一共出现了5次。

## 用例 1

**输入：** n = 12
**输出：** 5
## 用例 2

**输入：** n = 13
**输出：** 6

## 约束

1 <= n < 2^31
注意：本题与主站 233 题相同：https://leetcode-cn.com/problems/number-of-digit-one/

