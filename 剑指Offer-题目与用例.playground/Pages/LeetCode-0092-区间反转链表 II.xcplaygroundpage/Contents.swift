# LeetCode-0092-区间反转链表 II

## 题目

给定单链表的头节点 `head` 和两个整数 `left`、`right`，其中 `left <= right`。反转从位置 `left` 到位置 `right` 的链表节点，返回反转后的链表。

## 用例 1

**输入：** `head = [1,2,3,4,5]`，`left = 2`，`right = 4`

**输出：** `[1,4,3,2,5]`

## 用例 2

**输入：** `head = [5]`，`left = 1`，`right = 1`

**输出：** `[5]`

## 约束

- 链表节点数为 `n`
- `1 <= n <= 500`
- `-500 <= Node.val <= 500`
- `1 <= left <= right <= n`

