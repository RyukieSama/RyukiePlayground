func count(n: UInt32) -> Int {
    var n = n
    var result = 0
    
    while n != 0 {
        result += Int(n & 1)
        n >>= 1
    }
    
    return result
}


func count2(n: UInt32) -> Int {
    var count = 0
    var n = n
    
    while n != 0 {
        n = n & (n - 1)
        count += 1
    }
    
    return count
}


