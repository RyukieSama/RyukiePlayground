## 位运算解析

### 当前解法

当前实现使用 `UInt32` 保存无符号 32 位整数，并逐位检查最低位：

```swift
result += Int(n & 1)
```

`n & 1` 只保留二进制数的最低位：

- 结果为 `0`：最低位是 `0`
- 结果为 `1`：最低位是 `1`

统计后再右移一位：

```swift
n >>= 1
```

这样就可以依次检查每个二进制位。

例如 `11` 的二进制是 `1011`：

```text
1011 → 最低位 1
0101 → 最低位 1
0010 → 最低位 0
0001 → 最低位 1
```

最终得到 `3`。

### 为什么使用 `UInt32`

题目要求处理的是 32 位无符号整数。使用 `UInt32` 可以明确表示完整的 32 位范围，也不会因为有符号右移而产生符号扩展问题。

例如示例中的 `4294967293`，对应 32 位补码形式：

```text
11111111111111111111111111111101
```

使用 `UInt32` 可以正确统计出其中的 `31` 个 `1`。

### `count2`：消除最低位的 `1`

`count2` 使用下面这个位运算规律：

```swift
n = n & (n - 1)
```

对于任意非零整数，`n - 1` 会把 `n` 最右边的那个 `1` 变成 `0`，并把它右侧的 `0` 变成 `1`。再与原来的 `n` 做按位与后，右侧部分都会被清零，因此恰好消除最低位的一个 `1`。

例如：

```text
n     = 10110000
n - 1 = 10101111
n & (n - 1) = 10100000
```

可以看到，最右侧的 `1` 被消除了。

所以每次执行：

```swift
n = n & (n - 1)
count += 1
```

就代表已经统计出一个 `1`。当 `n` 变成 `0` 时，所有的 `1` 都已经被消除。

以 `11` 为例：

```text
1011 → 1010 → 1000 → 0000
```

一共执行 3 次，因此结果是 `3`。

这里不能写成：

```swift
count += n & (n - 1)
n >>= 1
```

因为按位与的结果是一个整数，不是单纯的计数值；而右移一位也不会保证每次只消除一个 `1`。

### 复杂度

- 当前逐位处理：最多检查 32 位，时间复杂度为 `O(32)`，空间复杂度为 `O(1)`。
- 使用 `n & (n - 1)`：时间复杂度为 `O(k)`，其中 `k` 是二进制中 `1` 的个数；空间复杂度仍为 `O(1)`。
