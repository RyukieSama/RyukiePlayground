# 44-数字序列中某一位的数字

## 题目

数字以0123456789101112131415…的格式序列化到一个字符序列中。

在这个序列中，第5位（从下标0开始计数）是5，第13位是1，第19位是4，等等。

请写一个函数，求任意第n位对应的数字。

## 用例 1

**输入：** n = 3
**输出：** 3
## 用例 2

**输入：** n = 11
**输出：** 0

## 约束

0 <= n < 2^31
注意：本题与主站 400 题相同：https://leetcode-cn.com/problems/nth-digit/

