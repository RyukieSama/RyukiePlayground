/*:
# 65-不用加减乘除做加法

## 题目

写一个函数，求两个整数之和，要求在函数体内不得使用 “+”、“-”、“*”、“/” 四则运算符号。

## 用例

**输入：** a = 1, b = 1

**输出：** 2

## 提示

a, b 均可能是负数或 0

结果不会溢出 32 位整数

## 来源

[LeetCode 原题](https://leetcode-cn.com/problems/bu-yong-jia-jian-cheng-chu-zuo-jia-fa-lcof)
*/
// 还是不太懂
func add(_ a: Int, _ b: Int) -> Int {
    var x = a
    var y = b
    
    while y != 0 {
        // 异或得到不包含进位的和。
        let sum = x ^ y
        
        // 两个位置同时为 1 时产生进位，左移一位表示进位到高位。
        let carry = (x & y) &<< 1
        
        x = sum
        y = carry
    }
    
    // 没有进位后，x 就是最终结果。
    return x
}

/*:
## 题目解析

二进制加法可以拆成两部分：计算不带进位的和，以及计算需要在下一轮处理的进位。

### 异或计算不带进位的和

`a ^ b` 的规则是两个二进制位不同为 `1`、相同为 `0`，正好对应不考虑进位的加法。

### 与运算计算进位

只有两个位置同时为 `1` 时才会产生进位，因此先使用 `a & b` 找到进位位置，再左移一位：

`(a & b) << 1`

代码使用 `&<<`，采用溢出截断的移位语义，适合处理符号位。

### 循环过程

每一轮：

- `sum = x ^ y`：当前不带进位的和；
- `carry = (x & y) &<< 1`：下一轮需要处理的进位。

将 `sum` 和 `carry` 作为新的两个数继续计算，直到 `carry == 0`。此时 `sum` 就是最终结果。

例如 `1 + 1`：

```text
sum = 1 ^ 1 = 0
carry = (1 & 1) << 1 = 2

sum = 0 ^ 2 = 2
carry = 0
```

最终结果为 `2`。

### 复杂度

- 时间复杂度：`O(1)`，整数位数固定；
- 额外空间复杂度：`O(1)`。
*/

