# 32-I-从上到下打印二叉树

## 题目

从上到下打印出二叉树的每个节点，同一层的节点按照从左到右的顺序打印。

例如:

给定二叉树: [3,9,20,null,null,15,7],

```
3
/ \
9  20
/  \
15   7
```

返回：

[3,9,20,15,7]

## 提示

节点总数 <= 1000

## 用例

**输入：** `root = [3,9,20,null,null,15,7]`

**输出：** `[3,9,20,15,7]`

