# 62-圆圈中最后剩下的数字

## 题目

0,1,···,n-1这n个数字排成一个圆圈，从数字0开始，每次从这个圆圈里删除第m个数字（删除后从下一个数字开始计数）。求出这个圆圈里剩下的最后一个数字。

例如，0、1、2、3、4这5个数字组成一个圆圈，从数字0开始每次删除第3个数字，则删除的前4个数字依次是2、0、4、1，因此最后剩下的数字是3。

## 用例 1

**输入：** n = 5, m = 3

**输出：** 3

## 用例 2

**输入：** n = 10, m = 17

**输出：** 2

## 约束

1 <= n <= 10^5
1 <= m <= 10^6

## 来源

[LeetCode 原题](https://leetcode-cn.com/problems/yuan-quan-zhong-zui-hou-sheng-xia-de-shu-zi-lcof)
*/

// 理解不能
func lastRemaining(_ n: Int, _ m: Int) -> Int {
    guard n > 0, m > 0 else {
        return -1
    }
    
    // 只有一个数字时，最后留下的下标一定是 0。
    var result = 0
    
    if n >= 2 {
        // 根据 f(size) = (f(size - 1) + m) % size，
        // 从 2 个数字逐步计算到 n 个数字。
        for size in 2...n {
            // 加上 m 表示删除位置带来的偏移，
            // 对 size 取模表示回到圆圈范围内。
            result = (result + m) % size
        }
    }
    
    return result
}

/*:
## 题目解析

这道题是经典的约瑟夫环问题。直接使用数组模拟删除，需要不断移动元素；使用链表虽然删除方便，但每次寻找第 `m` 个节点仍然需要遍历。更高效的方式是使用递推公式。

### 状态定义

设 `f(n)` 表示有 `n` 个数字、每次删除第 `m` 个数字时最后留下的数字下标。

当只有一个数字时：

```text
f(1) = 0
```

当规模从 `n - 1` 增加到 `n` 时，先删除一个数字，剩余数字组成一个规模为 `n - 1` 的相同问题。`f(n - 1)` 是在新起点下的结果，映射回原数组时需要向后偏移 `m`：

```text
f(n) = (f(n - 1) + m) % n
```

取模是因为数字排列在圆圈中，超过末尾后要重新回到开头。

### 迭代计算

从 `f(1)` 开始，依次计算 `f(2)`、`f(3)`，直到 `f(n)`。只需要保存上一次的结果，不需要保存整个圆圈：

```swift
var result = 0
for size in 2...n {
    result = (result + m) % size
}
```

### 示例：`n = 5, m = 3`

```text
f(1) = 0
f(2) = (0 + 3) % 2 = 1
f(3) = (1 + 3) % 3 = 1
f(4) = (1 + 3) % 4 = 0
f(5) = (0 + 3) % 5 = 3
```

因此最后剩下的数字是 `3`。

### 复杂度

- 时间复杂度：`O(n)`。
- 额外空间复杂度：`O(1)`。

这种方法不需要真正执行删除操作，只通过下标映射计算最后留下的位置。
*/


