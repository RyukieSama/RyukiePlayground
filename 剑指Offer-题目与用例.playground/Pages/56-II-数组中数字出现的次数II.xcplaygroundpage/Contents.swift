# 56-II-数组中数字出现的次数II

## 题目

在一个数组 nums 中除一个数字只出现一次之外，其他数字都出现了三次。请找出那个只出现一次的数字。

## 用例 1

**输入：** nums = [3,4,3,3]

**输出：** 4

## 用例 2

**输入：** nums = [9,1,7,9,7,9,7]

**输出：** 1

## 约束

1 <= nums.length <= 10000

1 <= nums[i] < 2^31

