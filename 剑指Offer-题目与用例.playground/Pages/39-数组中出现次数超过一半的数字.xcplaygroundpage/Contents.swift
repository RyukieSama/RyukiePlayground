# 39-数组中出现次数超过一半的数字

## 题目

数组中有一个数字出现的次数超过数组长度的一半，请找出这个数字。

你可以假设数组是非空的，并且给定的数组总是存在多数元素。

## 用例 1

**输入：** [1, 2, 3, 2, 2, 2, 5, 4, 2]
**输出：** 2

## 约束

1 <= 数组长度 <= 50000

注意：本题与主站 169 题相同：https://leetcode-cn.com/problems/majority-element/

## 来源

[LeetCode 原题](https://leetcode-cn.com/problems/majority-element/)
*/

func vote(nums: [Int]) -> Int? {
    guard nums.isEmpty == false else {
        return nil
    }
    var score = 0, x = 0
    
    for n in nums {
        if score == 0 { x = n }
        score += (x == n) ? 1 : -1
    }
    
    return x
}

/*:
## 题目解析

这道题要求找出数组中出现次数超过数组长度一半的数字。题目保证数组非空，并且一定存在这样的多数元素。

当前使用的是 **Boyer-Moore 投票算法**。

### 两个变量的含义

- `x`：当前候选数字。
- `score`：当前候选数字的相对票数。

遍历数组时：

- 当前数字等于候选值，`score += 1`；
- 当前数字不等于候选值，`score -= 1`；
- 当 `score == 0` 时，说明前面的候选值和其他数字已经互相抵消，需要把当前数字设置为新的候选值。

### 为什么可以抵消

多数元素出现次数超过其他所有数字出现次数之和。因此，即使把一个多数元素和一个非多数元素配成一对并抵消，多数元素最后仍然会剩余。

例如：

```text
[1, 2, 3, 2, 2, 2, 5, 4, 2]
```

每次遇到和候选值不同的数字，就抵消一票。由于 `2` 的数量超过数组长度的一半，所有抵消完成后，最后留下的候选值必然是 `2`。

### 当前实现评价

当前实现是正确的：

```swift
if score == 0 {
    x = n
}
score += (x == n) ? 1 : -1
```

先在票数为零时更新候选值，再根据当前数字是否与候选值相同调整票数，顺序没有问题。

数组为空时返回 `nil`，也属于合理的边界处理。虽然题目保证数组非空，但这样写可以避免空数组访问问题。

### 注意事项

如果题目不保证一定存在多数元素，那么最终的 `x` 只能看作候选值，还需要再次统计它出现的次数，确认是否超过 `nums.count / 2`。

本题已经保证多数元素存在，所以当前代码可以直接返回 `x`。

### 复杂度

- 时间复杂度：`O(n)`，只遍历数组一次。
- 额外空间复杂度：`O(1)`，只使用了候选值和票数两个变量。
*/

