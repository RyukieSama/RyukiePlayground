/*:
# 10-I-斐波那契数列

## 题目

写一个函数，输入 n ，求斐波那契（Fibonacci）数列的第 n 项（即 F(N)）。斐波那契数列的定义如下：

F(0) = 0,   F(1) = 1
F(N) = F(N - 1) + F(N - 2), 其中 N > 1.
斐波那契数列由 0 和 1 开始，之后的斐波那契数就是由之前的两数相加而得出。

答案需要取模 1e9+7（1000000007），如计算初始结果为：1000000008，请返回 1。

## 用例 1

**输入：** n = 2
**输出：** 1
## 用例 2

**输入：** n = 5
**输出：** 5

## 提示

0 <= n <= 100

## 来源

[LeetCode 原题](https://leetcode-cn.com/problems/fei-bo-na-qi-shu-lie-lcof)
*/
var d: [Int: Int] = [
    0: 0,
    1: 1
]

func fib(_ n: Int) -> Int {
    switch n {
    case 0:
        return 0
    case 1:
        return 1
    default:
        var res = 0
        if let v = d[n-1] {
            res += v
        }
        else {
            res += fib(n-1)
        }
        
        if let v = d[n-2] {
            res += v
        }
        else {
            res += fib(n-2)
        }
        d[n] = res
        return res
    }
}

fib(5)

/*:
## 记忆化递归：总结

### 当前实现的思路

函数使用递归计算斐波那契数列，并用全局字典 `d` 保存已经计算过的结果：

- `d[0] = 0`
- `d[1] = 1`
- 计算 `F(n)` 时，优先从字典中读取 `F(n - 1)` 和 `F(n - 2)`
- 只有缓存中没有对应值时，才继续递归计算

这种方法叫“记忆化递归”，本质上是自顶向下的动态规划。

### 正确的部分

如果不考虑取模要求，当前递归和缓存逻辑是正确的：

- 基础条件 `F(0) = 0`、`F(1) = 1` 正确。
- 每个状态只会真正计算一次。
- 已计算的结果会写入字典，避免重复递归。

### 主要错误：没有取模

题目要求所有结果对 `1_000_000_007` 取模，但当前代码在计算结果时直接执行：

```swift
res += v
```

当 `n` 较大时，斐波那契数会超过 Swift `Int` 的表示范围。题目允许
`n <= 100`，而 `F(93)` 已经超过 `Int64` 最大值，因此计算 `fib(100)`
时可能发生整数溢出并导致程序崩溃。

取模必须在每次加法后进行，并且写入字典的也应该是取模后的结果：

```
res = (前一项 + 前两项) % 1_000_000_007
```

这样每一项都会保持在较小范围内，后续加法也不会溢出。

### 复杂度

记忆化后，每个 `n` 只计算一次：

- 时间复杂度：`O(n)`
- 字典空间：`O(n)`
- 递归栈空间：`O(n)`
- 总额外空间复杂度：`O(n)`

如果使用循环并只保留前两个数字，可以将额外空间降为 `O(1)`。

### 其他注意事项

- 全局字典 `d` 会产生共享可变状态，建议实际实现时使用函数内部的 `memo`。
- `d` 这个名字不够明确，`memo` 或 `cache` 更容易理解。
- 当前没有处理负数 `n`，但题目约束保证 `n >= 0`，所以不影响本题。
- 基础值 `0` 和 `1` 没有写回字典，不影响正确性，但可以统一缓存。

### 最终结论

当前实现的“记忆化递归”框架是对的，但没有实现题目要求的取模操作。
因此它在小数值示例上正确，在 `n = 100` 等合法大输入上存在溢出风险。
